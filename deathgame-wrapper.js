function mergeRequirements(core, ext) {
  const merged = {};
  Object.keys(core).forEach(id => {
    merged[id] = Object.assign({}, core[id], ext[id] || {});
  });
  return merged;
}

function mergeCases(core, ext) {
  const merged = {};
  Object.keys(core).forEach(id => {
    merged[id] = Object.assign({}, core[id], ext[id] || {});
  });
  return merged;
}

